import numpy as np

print("Zeros:")
print(np.zeros((2, 3)))

print("\nOnes:")
print(np.ones((2, 3)))

print("\nFull:")
print(np.full((2, 3), 7))

print("\nRange:")
print(np.arange(0, 10, 2))

print("\nEvenly spaced values:")
print(np.linspace(0, 1, 5))

print("\nIdentity matrix:")
print(np.eye(3))

print("\nRandom values:")
print(np.random.rand(2, 3))
