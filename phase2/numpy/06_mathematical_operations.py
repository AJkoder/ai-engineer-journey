import numpy as np

a = np.array([10, 20, 30])
b = np.array([1, 2, 3])

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

print("Square:", np.square(a))
print("Square root:", np.sqrt(a))
print("Power:", np.power(a, 2))

print("Sum:", np.sum(a))
print("Minimum:", np.min(a))
print("Maximum:", np.max(a))
